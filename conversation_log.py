# Seeding: the Copilot session store
# --------------------------------------------------------------------------

class SeedReport:
    """What a seed run did, in enough detail to be worth reading twice.

    Two fields carry most of the weight.

    ``skipped`` distinguishes "nothing new" from "silently rejected
    everything", which are the two outcomes a re-run exists to tell apart.

    ``absent`` separates *this source is not on this machine* from *this source
    is here and would not read*. Only the second is a failure. A machine that
    has never run a peer agent has no mail directory, and a seeder that exits
    non-zero over it is one that fails on a clean install -- while a mail
    directory that exists and throws is exactly the case that must not be
    swallowed.
    """

    def __init__(self, source: str) -> None:
        self.source = source
        self.added = 0
        self.duplicate = 0
        self.skipped: dict[str, int] = {}
        self.errors: list[str] = []
        self.absent: str = ""

    def skip(self, reason: str) -> None:
        self.skipped[reason] = self.skipped.get(reason, 0) + 1

    @property
    def failed(self) -> bool:
        return bool(self.errors)

    def describe(self) -> str:
        if self.absent and not self.errors:
            return f"{self.source}: nothing to read ({self.absent})"
        parts = [f"{self.source}: {self.added} added",
                 f"{self.duplicate} already present"]
        for reason, count in sorted(self.skipped.items()):
            parts.append(f"{count} skipped ({reason})")
        if self.errors:
            parts.append(f"{len(self.errors)} error(s)")
        return ", ".join(parts)


def seed_session_store(conn: sqlite3.Connection,
                       store: "Path | None" = None) -> SeedReport:
    """Copy human/agent turns out of the Copilot CLI's own session store.

    Read-only, and opened read-only: this is somebody else's live database and
    the tool has no business being able to write to it even by mistake.
    """
    report = SeedReport(SOURCE_SESSION_STORE)
    path = Path(store) if store is not None else copilot_home() / "session-store.db"
    present = install_manifest.file_present(path)
    if present is False:
        report.absent = f"no session store at {path}"
        return report
    if present is None:
        # Occupied but unexaminable. Reporting that as absent would say "you
        # have no session history" about a machine that has years of it, and
        # `absent` is the answer that exits 0 -- so the wrong branch here is
        # silent data loss dressed as a clean install.
        report.errors.append(
            f"could not determine whether {path} exists (permissions?)")
        return report
    try:
        src = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    except sqlite3.Error as exc:
        report.errors.append(f"could not open {path}: {exc}")
        return report
    src.row_factory = sqlite3.Row
    try:
        rows = src.execute(
            "SELECT t.session_id, t.turn_index, t.user_message,"
            "       t.assistant_response, t.timestamp,"
            "       s.repository, s.cwd, s.branch"
            "  FROM turns t LEFT JOIN sessions s ON s.id = t.session_id"
            " ORDER BY t.session_id, t.turn_index").fetchall()
    except sqlite3.Error as exc:
        report.errors.append(f"could not read turns: {exc}")
        src.close()
        return report

    for row in rows:
        context = {
            "repository": row["repository"] or "",
            "cwd": row["cwd"] or "",
            "branch": row["branch"] or "",
            "session_id": row["session_id"] or "",
        }
        stamp = row["timestamp"] or ""
        prompt = row["user_message"] or ""
        actor, channel, sender = classify(prompt)
        if channel == AGENT_AGENT:
            # Owned by the mail store; see peer_sender().
            report.skip("peer message, held by operator mail")
        elif not prompt.strip():
            report.skip("empty prompt")
        else:
            added = record(
                conn, source=SOURCE_SESSION_STORE,
                source_id=f'{row["session_id"]}:{row["turn_index"]}:in',
                body=prompt, direction=INBOUND, sent_at=stamp,
                actor=actor, channel=channel, sender=sender, **context)
            report.added += 1 if added else 0
            report.duplicate += 0 if added else 1

        reply = row["assistant_response"] or ""
        if not reply.strip():
            report.skip("empty response")
            continue
        added = record(
            conn, source=SOURCE_SESSION_STORE,
            source_id=f'{row["session_id"]}:{row["turn_index"]}:out',
            body=reply, direction=OUTBOUND, sent_at=stamp,
            actor=AGENT, channel=HUMAN_AGENT, **context)
        report.added += 1 if added else 0
        report.duplicate += 0 if added else 1

    src.close()
    conn.commit()
    return report


# --------------------------------------------------------------------------
# Seeding: operator mail
# --------------------------------------------------------------------------

def seed_operator_mail(conn: sqlite3.Connection,
                       root: "Path | None" = None) -> SeedReport:
    """Copy agent-to-agent mail out of ``~/.operator/messages``.

    Both the inbox and its archive are read. A message is filed once, under its
    own id, so a message that moves from inbox to archive between two runs is
    not counted twice -- which is the normal life of every message here.
    """
    report = SeedReport(SOURCE_OPERATOR_MAIL)
    base = Path(root) if root is not None else operator_home() / "messages"
    present = install_manifest.dir_present(base)
    if present is False:
        report.absent = f"no mail directory at {base}"
        return report
    if present is None:
        report.errors.append(
            f"could not determine whether {base} exists (permissions?)")
        return report
    for path in sorted(set(base.glob("**/*.json"))):
        try:
            msg = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            report.errors.append(f"{path.name}: {exc}")
            continue
        if not isinstance(msg, dict):
            report.skip("not a message object")
            continue
        text = msg.get("text") or ""
        if not str(text).strip():
            report.skip("empty message")
            continue
        # The recipient's inbox names the instance; that is the best "project"
        # signal mail carries, and it is a weak one, so it is stored as the
        # instance and left out of `project` rather than guessed at.
        recipient = str(msg.get("to") or "")
        identity = str(msg.get("id") or "")
        if not identity:
            # Fall back to the filename, which encodes timestamp and a hash.
            identity = path.stem
            report.skip("message had no id; used filename")
        added = record(
            conn, source=SOURCE_OPERATOR_MAIL, source_id=identity,
            body=str(text), direction=INBOUND,
            sent_at=str(msg.get("sent_at") or ""),
            channel=AGENT_AGENT, actor=AGENT,
            sender=str(msg.get("from") or ""), recipient=recipient,
            instance=str(msg.get("to_id") or recipient))
        report.added += 1 if added else 0
        report.duplicate += 0 if added else 1
    conn.commit()
    return report


