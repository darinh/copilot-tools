def spool_dir(home: "Path | None" = None) -> Path:
    """Where the capture extension appends what it sees.

    The extension writes JSON lines rather than rows. That keeps every
    classification rule in this module -- a capture path that re-implemented
    them in JavaScript would agree with the seeder right up until one of the
    two was edited -- and an append-only file needs no lock against a viewer
    reading the database.
    """
    return (Path(home) if home is not None else operator_home()) / "conversation-spool"


def ingest_spool(conn: sqlite3.Connection,
                 directory: "Path | None" = None) -> SeedReport:
    """Fold captured events into the store.

    Spool files are kept, not consumed. Re-reading them is free -- the natural
    key rejects what is already stored -- and a crash between reading and
    committing would otherwise lose the only copy.
    """
    report = SeedReport(SOURCE_HOOK)
    base = Path(directory) if directory is not None else spool_dir()
    present = install_manifest.dir_present(base)
    if present is False:
        report.absent = f"nothing captured yet at {base}"
        return report
    if present is None:
        report.errors.append(
            f"could not determine whether {base} exists (permissions?)")
        return report
    for path in sorted(base.glob("*.jsonl")):
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError as exc:
            report.errors.append(f"{path.name}: {exc}")
            continue
        for number, line in enumerate(lines, 1):
            if not line.strip():
                continue
            try:
                event = json.loads(line)
            except ValueError:
                # A partially written final line is expected: the writer is a
                # live session and may be mid-append. Counted, not fatal.
                report.skip("unparseable line")
                continue
            if not isinstance(event, dict):
                report.skip("not an event object")
                continue
            body = str(event.get("body") or "")
            direction = str(event.get("direction") or "")
            if direction not in (INBOUND, OUTBOUND):
                report.skip("unknown direction")
                continue
            if not body.strip():
                report.skip("empty body")
                continue
            if direction == INBOUND and peer_sender(body) is not None:
                report.skip("peer message, held by operator mail")
                continue
            identity = str(event.get("id") or f"{path.stem}:{number}")
            actor = channel = None
            sender = ""
            if direction == INBOUND:
                actor, channel, sender = classify(body)
            added = record(
                conn, source=SOURCE_HOOK, source_id=identity, body=body,
                direction=direction, sent_at=str(event.get("sent_at") or ""),
                cwd=str(event.get("cwd") or ""),
                session_id=str(event.get("session_id") or ""),
                actor=actor, channel=channel, sender=sender)
            report.added += 1 if added else 0
            report.duplicate += 0 if added else 1
    conn.commit()
    return report


def seed_all(conn: sqlite3.Connection) -> list[SeedReport]:
    return [seed_session_store(conn), seed_operator_mail(conn),
            ingest_spool(conn)]


