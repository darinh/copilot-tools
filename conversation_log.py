#: Values the viewer will accept for `channel`, `direction` and `actor`.
#: Filters are matched against these rather than interpolated, so a query
#: string cannot reach the SQL.
_ENUMS = {
    "channel": (HUMAN_AGENT, AGENT_AGENT),
    "direction": (INBOUND, OUTBOUND),
    "actor": (HUMAN, AGENT, SYSTEM),
}


def _fts_query(text: str) -> str:
    """Turn user input into an FTS5 MATCH expression that cannot be malformed.

    Every term is quoted and the terms are ANDed. FTS5's query language treats
    ``-``, ``*``, ``:``, ``(`` and ``"`` as syntax, so a search for a filename
    or a flag -- exactly what gets searched for here -- raises rather than
    returning nothing, and an error page for `--force` would be absurd.

    Split on ``[\\W_]+`` rather than ``[^\\w]+`` because the two disagree about
    one character and the disagreement is silent. Python's ``\\w`` includes
    ``_``; FTS5's unicode61 tokeniser treats it as a separator. So a search for
    ``_`` produced the term ``_``, this returned the non-empty expression
    ``"_"``, the caller took that as "FTS can answer this" -- and FTS then
    tokenised it away to an empty phrase and matched nothing. Two rows on the
    test machine contain ``_`` and the search for it found neither, with no
    error and no fallback. Splitting on FTS's own separator set makes the
    emptiness test agree with the engine that has to run the query.
    """
    terms = [t for t in re.split(r"[\W_]+", text) if t]
    return " AND ".join('"' + t + '"' for t in terms)


def _like_term(text: str) -> str:
    """Escape the wildcards LIKE would otherwise read as syntax.

    ``%`` and ``_`` are LIKE's own metacharacters, so an unescaped search for
    ``100%`` matches every row whose body contains ``100`` followed by
    anything, and one for ``a_b`` matches ``axb``. Both return *more* rows
    than asked for, which is the failure that does not look like one.
    """
    return (text.replace("\\", "\\\\")
                .replace("%", "\\%")
                .replace("_", "\\_"))


def query(conn: sqlite3.Connection, *, search: str = "", project: str = "",
          channel: str = "", direction: str = "", actor: str = "",
          instance: str = "", date_from: str = "", date_to: str = "",
          session_id: str = "", asks: bool = False,
          limit: int = 200, offset: int = 0) -> list[dict]:
    """Messages matching the given filters, newest first."""
    where: list[str] = []
    params: list[object] = []

    if asks:
        # In SQL, not in the caller. The viewer filtered the returned page,
        # which applies the filter *after* LIMIT: one old question behind 200
        # newer statements returned nothing at all, and "no questions" is
        # indistinguishable from "none in the last 200 rows".
        where.append("m.asks = 1")

    if search.strip():
        if "\x00" in search:
            # A NUL cannot occur in a stored body -- these come from JSON and
            # from SQLite TEXT -- so this search matches nothing. Saying that
            # explicitly matters because the alternative is not "no rows": a
            # NUL in a bound LIKE parameter truncates the pattern at the NUL,
            # so `%\x00%` degenerates to `%` and every row comes back. That is
            # the same match-everything failure this branch was rewritten to
            # remove, reachable through the rewrite.
            where.append("1 = 0")
        else:
            expr = _fts_query(search) if search_mode(conn) == "fts" else ""
            if expr:
                where.append("m.id IN (SELECT rowid FROM messages_fts "
                             "WHERE messages_fts MATCH ?)")
                params.append(expr)
            else:
                # Either there is no FTS index, or the search is all
                # punctuation -- `(`, `*`, `-->` -- which FTS5's tokeniser
                # discards entirely, leaving an empty MATCH expression.
                #
                # Dropping the predicate here is what this branch used to do,
                # and it is the worst of the three options: the user searches
                # for `(`, every row comes back, and a result set that means
                # "no filter was applied" is indistinguishable from one that
                # means "everything matched". Returning nothing would at least
                # be honest, but it is still wrong -- there really are rows
                # containing `(`, and the substring path can find them. So
                # punctuation searches take the same route as a machine with
                # no FTS5, which also keeps the two modes returning the same
                # rows for the same query.
                where.append("m.body LIKE ? ESCAPE '\\'")
                params.append(f"%{_like_term(search.strip())}%")

    for column, value in (("project", project), ("instance", instance),
                          ("session_id", session_id)):
        if value:
            where.append(f"m.{column} = ?")
            params.append(value)

    for column, value in (("channel", channel), ("direction", direction),
                          ("actor", actor)):
        if value:
            if value not in _ENUMS[column]:
                raise ConversationError(f"unknown {column}: {value!r}")
            where.append(f"m.{column} = ?")
            params.append(value)

    # Dates are compared on the 10-character prefix so a caller can pass a day
    # without having to know how the timestamp is spelled.
    if date_from:
        where.append("substr(m.sent_at, 1, 10) >= ?")
        params.append(date_from[:10])
    if date_to:
        where.append("substr(m.sent_at, 1, 10) <= ?")
        params.append(date_to[:10])

    clause = (" WHERE " + " AND ".join(where)) if where else ""
    sql = (f"SELECT m.* FROM messages m{clause} "
           f"ORDER BY m.sent_at DESC, m.id DESC LIMIT ? OFFSET ?")
    params.extend([max(1, min(int(limit), 1000)), max(0, int(offset))])
    return [dict(r) for r in conn.execute(sql, params)]


def projects(conn: sqlite3.Connection) -> list[dict]:
    rows = conn.execute(
        "SELECT project, COUNT(*) AS messages,"
        "       MIN(substr(sent_at, 1, 10)) AS first_day,"
        "       MAX(substr(sent_at, 1, 10)) AS last_day"
        "  FROM messages WHERE project <> ''"
        " GROUP BY project ORDER BY MAX(sent_at) DESC")
    return [dict(r) for r in rows]


def days(conn: sqlite3.Connection, project: str = "") -> list[dict]:
    sql = ("SELECT substr(sent_at, 1, 10) AS day, COUNT(*) AS messages"
           "  FROM messages")
    params: list[object] = []
    if project:
        sql += " WHERE project = ?"
        params.append(project)
    sql += " GROUP BY day ORDER BY day DESC"
    return [dict(r) for r in conn.execute(sql, params)]


def instances(conn: sqlite3.Connection) -> list[str]:
    rows = conn.execute(
        "SELECT DISTINCT instance FROM messages"
        " WHERE instance <> '' ORDER BY instance")
    return [r["instance"] for r in rows]


def summary(conn: sqlite3.Connection) -> dict:
    row = conn.execute(
        "SELECT COUNT(*) AS messages,"
        "       COUNT(DISTINCT project) AS projects,"
        "       COUNT(DISTINCT session_id) AS sessions,"
        "       MIN(substr(sent_at, 1, 10)) AS first_day,"
        "       MAX(substr(sent_at, 1, 10)) AS last_day"
        "  FROM messages").fetchone()
    out = dict(row) if row else {}
    by_channel = conn.execute(
        "SELECT channel, actor, COUNT(*) AS n FROM messages"
        " GROUP BY channel, actor")
    out["breakdown"] = [dict(r) for r in by_channel]
    out["search_mode"] = search_mode(conn)
    return out
